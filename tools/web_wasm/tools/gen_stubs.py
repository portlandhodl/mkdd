#!/usr/bin/env python3
"""Generate typed no-op definitions for SDK functions the port still lacks.

    python tools/web_wasm/tools/gen_stubs.py [build/web_wasm/undefined.txt] > tools/web_wasm/sdk/stubs_auto.c
Reads declarations from tools/web_wasm/sdk/sdk_all.h via clang's JSON AST so the wasm
signatures match the callers. Symbols already defined in tools/web_wasm/sdk, tools/web_wasm/gpu, libs/dolphin/gd or libs/dolphin/gx are skipped.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
FLAGS = open(os.path.join(ROOT, "tools/web_wasm/tools/flags.txt")).read().split()
DROP = {"-fsyntax-only", "-std=gnu++03", "-fdelayed-template-parsing", "-fms-compatibility"}

def decls():
    flags = [f for f in FLAGS if f not in DROP]
    r = subprocess.run(["clang", "-x", "c", "-std=gnu99", *flags, "-fsyntax-only", "-Xclang", "-ast-dump=json",
                        "tools/web_wasm/sdk/sdk_all.h"], cwd=ROOT, capture_output=True, text=True, check=True)
    out = {}
    for n in json.loads(r.stdout)["inner"]:
        if n.get("kind") == "FunctionDecl" and n.get("storageClass") != "static" and "name" in n:
            params = [(p.get("name"), p["type"]["qualType"]) for p in n.get("inner", []) if p.get("kind") == "ParmVarDecl"]
            out[n["name"]] = (n["type"]["qualType"], params, n.get("variadic", False))
    return out

def ret_type(fn_type):
    depth = 0
    for i, c in enumerate(fn_type):
        if c == "(":
            if depth == 0 and i and fn_type[:i].strip():
                return fn_type[:i].strip()
            depth += 1
        elif c == ")":
            depth -= 1
    return fn_type.split("(")[0].strip()

def decl_param(t, name):
    m = re.search(r"\(\*\)", t)
    if m:
        return t[:m.start()] + f"(*{name})" + t[m.end():]
    m = re.search(r"\[(\d*)\]", t)
    if m:
        return t[:m.start()].rstrip() + f" {name}" + t[m.start():]
    return f"{t} {name}"

def main():
    want = [l.strip() for l in open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build/web_wasm/undefined.txt"))]
    have = set()
    for d in ("tools/web_wasm/sdk", "tools/web_wasm/gpu", "libs/dolphin/gd", "libs/dolphin/gx"):
        for f in os.listdir(os.path.join(ROOT, d)):
            if f.endswith((".c", ".cpp")) and f != "stubs_auto.c":
                src = open(os.path.join(ROOT, d, f)).read()
                src = re.sub(r"/\*.*?\*/|//[^\n]*", "", src, flags=re.S)
                have.update(re.findall(r"\b(\w+)\s*\([^;{}]*\)\s*\{", src))
    d = decls()
    print("/* Generated by tools/web_wasm/tools/gen_stubs.py: no-op SDK functions not yet implemented. */")
    print('#include "sdk_all.h"\n#include "port_sdk.h"\n')
    for s in want:
        if s not in d or s in have:
            continue
        fty, params, variadic = d[s]
        rt = ret_type(fty)
        ps = ", ".join(decl_param(t, n or f"a{i}") for i, (n, t) in enumerate(params)) or "void"
        if variadic:
            ps += ", ..."
        body = f'    MKDD_STUB("{s}");'
        if rt != "void":
            body += f"\n    {{ {rt} r; __builtin_memset(&r, 0, sizeof r); return r; }}"
        print(f"{rt} {s}({ps})\n{{\n{body}\n}}\n")

if __name__ == "__main__":
    main()
